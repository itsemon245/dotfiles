"""Generate SSH aliases for Warpgate targets from a short TOML list.

The TOML (default ~/.ssh/warpgate/hosts.toml) lists Warpgate target names. Each target
gets an alias worked out from its name:

  acme-corp-backend-01    ->  acme-prod1      (backend is the default role)
  acme-corp-db-stage      ->  acme-stage-db
  ffmpeg-dev-shop-01      ->  shop-dev-ffmpeg1

Targets sit at the bottom in [targets], one plain list per group (the group names are
only labels). When the rules guess wrong, [overrides] sets a target's alias, env, user,
port or identity_file. The result is written next to the TOML as ~/.ssh/warpgate/hosts.conf,
after showing a diff and asking. ~/.ssh/config needs `Include warpgate/*.conf` at the top.

Commands:
  warpgate-ssh              generate, show the diff, ask, write
  warpgate-ssh --list       print target -> alias without writing
  warpgate-ssh --check      exit 1 if the generated file is out of date
  warpgate-ssh add          read pasted `ssh ... 'user:target@gate...'` lines (or bare
                            target names) from stdin, add new ones to the TOML, then generate
"""

from __future__ import annotations

import argparse
import difflib
import fnmatch
import re
import shlex
import shutil
import sys
import tomllib
from dataclasses import dataclass
from datetime import datetime
from pathlib import Path

from .cli import ToolError
from .paths import expand, home, xdg_state_home

HEADER = "# Generated by warpgate-ssh from {source}. Do not edit: change the TOML and rerun warpgate-ssh."
ALIAS_PATTERN = re.compile(r"^[a-z0-9][a-z0-9.-]*$")
TARGET_PATTERN = re.compile(r"^[A-Za-z0-9][A-Za-z0-9._-]*$")
PASTED_TARGET = re.compile(r"[A-Za-z0-9._-]+:([A-Za-z0-9][A-Za-z0-9._-]*)@")
COLORS = {
    "red": (200, 30, 30),
    "orange": (240, 150, 20),
    "yellow": (230, 200, 40),
    "green": (40, 140, 60),
    "blue": (40, 100, 200),
    "purple": (130, 60, 180),
    "gray": (110, 110, 110),
}

TOP_KEYS = {"gateway", "vpn", "projects", "rules", "banners", "overrides", "targets"}
GATEWAY_KEYS = {"host", "port", "user", "identity_file", "prefix", "connect_timeout"}
VPN_KEYS = {"interface"}
PROJECT_KEYS = {"name", "match", "user", "port", "identity_file"}
RULE_KEYS = {"default_env", "default_role", "envs", "ignore"}
BANNER_KEYS = {"label", "color"}
OVERRIDE_KEYS = {"alias", "env", "user", "port", "identity_file"}
NO_ENV = "none"


@dataclass(frozen=True)
class Project:
    key: str
    name: str
    match: tuple[tuple[str, ...], ...]  # token sequences that identify the project
    user: str | None
    port: int | None
    identity_file: str | None


@dataclass(frozen=True)
class Server:
    target: str
    aliases: tuple[str, ...]  # without the prefix
    env: str | None
    project: Project | None
    user: str
    port: int | None  # only when it differs from the gateway port
    identity_file: str | None  # only when it differs from the gateway key


@dataclass(frozen=True)
class Config:
    source: Path
    host: str
    port: int
    user: str
    identity_file: str
    prefix: str
    connect_timeout: int
    interface: str
    projects: tuple[Project, ...]
    default_env: str
    default_role: str
    envs: dict[str, str]  # name token -> env
    ignore: frozenset[str]
    banners: dict[str, tuple[str, tuple[int, int, int]]]  # env -> (label, rgb); "default" is the fallback
    targets: tuple[str, ...]
    overrides: dict[str, dict]  # target -> settings that replace the derived ones


def warpgate_dir() -> Path:
    return home() / ".ssh" / "warpgate"


def default_config_path() -> Path:
    return warpgate_dir() / "hosts.toml"


def default_output_path() -> Path:
    return warpgate_dir() / "hosts.conf"


def backup_root() -> Path:
    return xdg_state_home() / "dotfiles" / "backups" / "warpgate-ssh"


# ── Loading ──────────────────────────────────────────────────────────────────


def _table(data: dict, key: str, allowed: set[str], where: str) -> dict:
    value = data.get(key, {})
    if not isinstance(value, dict):
        raise ToolError(f"{where}: [{key}] must be a table")
    _only(value, allowed, f"{where} [{key}]")
    return value


def _only(table: dict, allowed: set[str], where: str) -> None:
    unknown = sorted(set(table) - allowed)
    if unknown:
        raise ToolError(f"{where}: unknown key(s) {', '.join(unknown)} (allowed: {', '.join(sorted(allowed))})")


def _tokens(text: str) -> tuple[str, ...]:
    return tuple(token for token in re.split(r"[-._]+", text.lower()) if token)


def _color(value: str, where: str) -> tuple[int, int, int]:
    if value in COLORS:
        return COLORS[value]
    match = re.fullmatch(r"#([0-9a-fA-F]{6})", value)
    if not match:
        raise ToolError(f"{where}: color must be one of {', '.join(COLORS)} or #rrggbb, got {value!r}")
    raw = match.group(1)
    return int(raw[0:2], 16), int(raw[2:4], 16), int(raw[4:6], 16)


def _port(value, where: str) -> int | None:
    if value is None:
        return None
    if not isinstance(value, int) or not 0 < value < 65536:
        raise ToolError(f"{where}: port must be a number between 1 and 65535")
    return value


def load_config(path: Path) -> Config:
    try:
        data = tomllib.loads(path.read_text(encoding="utf-8"))
    except FileNotFoundError:
        raise ToolError(f"{path} not found") from None
    except tomllib.TOMLDecodeError as exc:
        raise ToolError(f"{path}: {exc}") from None
    where = str(path)
    _only(data, TOP_KEYS, where)

    gateway = _table(data, "gateway", GATEWAY_KEYS, where)
    for key in ("host", "user", "identity_file"):
        if not isinstance(gateway.get(key), str) or not gateway[key]:
            raise ToolError(f"{where} [gateway]: {key} is required")
    vpn = _table(data, "vpn", VPN_KEYS, where)
    rules = _table(data, "rules", RULE_KEYS, where)

    projects = []
    for key, spec in data.get("projects", {}).items():
        if not isinstance(spec, dict):
            raise ToolError(f"{where} [projects]: {key} must be a table, e.g. {key} = {{}}")
        _only(spec, PROJECT_KEYS, f"{where} [projects] {key}")
        name = spec.get("name", key)
        names = [name, *spec.get("match", [])]
        projects.append(
            Project(
                key=key,
                name=name,
                match=tuple(_tokens(item) for item in names),
                user=spec.get("user"),
                port=_port(spec.get("port"), f"{where} [projects] {key}"),
                identity_file=spec.get("identity_file"),
            )
        )

    envs: dict[str, str] = {}
    for env, words in rules.get("envs", {"stage": ["stage", "staging"], "dev": ["dev"]}).items():
        for word in words:
            envs[word.lower()] = env

    banners = {"default": ("SERVER", COLORS["green"])}
    for env, spec in data.get("banners", {}).items():
        if not isinstance(spec, dict):
            raise ToolError(f"{where} [banners]: {env} must be a table")
        _only(spec, BANNER_KEYS, f"{where} [banners] {env}")
        banners[env] = (spec.get("label", env.upper()), _color(spec.get("color", "green"), f"{where} [banners] {env}"))

    groups = data.get("targets", {})
    if not isinstance(groups, dict):
        raise ToolError(f"{where}: targets must be a [targets] table of lists, e.g. [targets]\nmyproject = [\"myproject-backend-01\"]")
    targets: list[str] = []
    for group, names in groups.items():
        if not isinstance(names, list) or not all(isinstance(name, str) for name in names):
            raise ToolError(f"{where} [targets] {group}: must be a list of target names; per-target settings go in [overrides]")
        targets += names

    overrides = data.get("overrides", {})
    if not isinstance(overrides, dict):
        raise ToolError(f"{where}: [overrides] must be a table")
    for target, spec in overrides.items():
        if not isinstance(spec, dict):
            raise ToolError(f'{where} [overrides] "{target}": must be a table, e.g. {{ alias = "..." }}')
        _only(spec, OVERRIDE_KEYS, f'{where} [overrides] "{target}"')
    unknown = sorted(set(overrides) - set(targets))
    if unknown:
        raise ToolError(f"{where} [overrides]: not listed in [targets]: {', '.join(unknown)}")

    return Config(
        source=path,
        host=gateway["host"],
        port=_port(gateway.get("port", 22), f"{where} [gateway]") or 22,
        user=gateway["user"],
        identity_file=gateway["identity_file"],
        prefix=gateway.get("prefix", ""),
        connect_timeout=_port(gateway.get("connect_timeout", 10), f"{where} [gateway] connect_timeout") or 10,
        interface=vpn.get("interface", ""),
        projects=tuple(projects),
        default_env=rules.get("default_env", "prod"),
        default_role=rules.get("default_role", "backend"),
        envs=envs,
        ignore=frozenset(word.lower() for word in rules.get("ignore", ["ai", "com", "io", "net", "org"])),
        banners=banners,
        targets=tuple(targets),
        overrides=overrides,
    )


# ── Working out aliases ──────────────────────────────────────────────────────


def _find(tokens: list[str], sequence: tuple[str, ...]) -> int:
    for start in range(len(tokens) - len(sequence) + 1):
        if tuple(tokens[start : start + len(sequence)]) == sequence:
            return start
    return -1


def _match_project(tokens: list[str], projects: tuple[Project, ...]) -> tuple[Project | None, list[str]]:
    best: tuple[int, Project, int] | None = None  # (length, project, start)
    for project in projects:
        for sequence in project.match:
            start = _find(tokens, sequence)
            if start >= 0 and (best is None or len(sequence) > best[0]):
                best = (len(sequence), project, start)
    if best is None:
        return None, tokens
    length, project, start = best
    return project, tokens[:start] + tokens[start + length :]


def derive(target: str, config: Config) -> tuple[Project | None, str | None, str]:
    """Return (project, env, alias) for a target name. Targets outside every project keep their name."""
    tokens = [token for token in _tokens(target) if token not in config.ignore]
    project, rest = _match_project(tokens, config.projects)
    if project is None:
        return None, None, "-".join(_tokens(target))

    env = config.default_env
    for token in rest:
        if token in config.envs:
            env = config.envs[token]
    rest = [token for token in rest if token not in config.envs]
    numbers = [str(int(token)) for token in rest if token.isdigit()]
    role = [token for token in rest if not token.isdigit() and token != config.default_role]

    alias = "-".join([project.key, env, *role]) + "".join(numbers)
    return project, env, alias


def _full_name_alias(alias: str, project: Project | None) -> str | None:
    if project is None or project.name == project.key or not alias.startswith(project.key + "-"):
        return None
    return project.name + alias[len(project.key) :]


def resolve(config: Config) -> list[Server]:
    servers = []
    for target in config.targets:
        where = f"{config.source}: {target}"
        if not TARGET_PATTERN.match(target):
            raise ToolError(f"{config.source} [targets]: {target!r} is not a Warpgate target name")
        entry = config.overrides.get(target, {})

        project, env, alias = derive(target, config)
        alias = entry.get("alias", alias)
        if "env" in entry:
            env = None if entry["env"] == NO_ENV else entry["env"]
        aliases = [alias]
        full = _full_name_alias(alias, project)
        if full:
            aliases.append(full)
        for name in aliases:
            if not ALIAS_PATTERN.match(name):
                raise ToolError(f"{where}: alias {name!r} may only use a-z, 0-9, '.' and '-'")

        def pick(key):
            if key in entry:
                return entry[key]
            return getattr(project, key, None) if project else None

        port = _port(pick("port"), where)
        identity_file = pick("identity_file")
        servers.append(
            Server(
                target=target,
                aliases=tuple(aliases),
                env=env,
                project=project,
                user=pick("user") or config.user,
                port=port if port not in (None, config.port) else None,
                identity_file=identity_file if identity_file not in (None, config.identity_file) else None,
            )
        )
    _check_unique(servers, config)
    return servers


def _check_unique(servers: list[Server], config: Config) -> None:
    seen_targets: dict[str, int] = {}
    seen_aliases: dict[str, str] = {}
    for server in servers:
        if server.target in seen_targets:
            raise ToolError(f"{config.source}: target {server.target} is listed twice")
        seen_targets[server.target] = 1
        for alias in server.aliases:
            other = seen_aliases.get(alias)
            if other:
                raise ToolError(
                    f"{config.source}: {other} and {server.target} both become {full_alias(alias, config)}; "
                    f'give one of them its own alias under [overrides]: "{server.target}" = {{ alias = "..." }}'
                )
            seen_aliases[alias] = server.target


def full_alias(alias: str, config: Config) -> str:
    return f"{config.prefix}-{alias}" if config.prefix else alias


# ── Rendering ────────────────────────────────────────────────────────────────


def _banner_command(label: str, rgb: tuple[int, int, int]) -> str:
    red, green, blue = rgb
    text = "0;0;0" if (0.299 * red + 0.587 * green + 0.114 * blue) > 150 else "255;255;255"
    # Only when ssh's stdout is a terminal (an interactive login). For scp, rsync, git, IDEs
    # and `ssh host cmd | ...` stdout is the data stream, and the banner would corrupt it.
    return f"test -t 1 && printf '\\033[1;38;2;{text};48;2;{red};{green};{blue}m  {label}: %n  \\033[0m\\n'"


def _vpn_down_proxy(config: Config) -> str:
    """A ProxyCommand that prints the warning and fails, so ssh stops instead of hanging."""
    warning = f"  NetBird VPN is not connected ({config.interface} is down). Connect first: netbird up  "
    return f"""sh -c 'printf "\\033[1;38;2;0;0;0;48;2;230;200;40m{warning}\\033[0m\\n" >&2; exit 1'"""


def _banner_patterns(config: Config) -> list[tuple[str, list[str]]]:
    """(env, alias patterns) in banner order. An env matches aliases containing -<env> or one of its words."""
    result = []
    for env in config.banners:
        if env == "default":
            continue
        words = [env, *(word for word, mapped in config.envs.items() if mapped == env)]
        result.append((env, [f"*-{word}*" for word in dict.fromkeys(words)]))
    return result


def _banner_by_pattern(alias: str, patterns: list[tuple[str, list[str]]]) -> str:
    for env, globs in patterns:
        if any(fnmatch.fnmatchcase(alias, glob) for glob in globs):
            return env
    return "default"


def render(config: Config, servers: list[Server]) -> str:
    try:
        source = "~/" + str(config.source.resolve().relative_to(home().resolve()))
    except ValueError:
        source = str(config.source)
    lines = [HEADER.format(source=source), ""]
    patterns = _banner_patterns(config)

    current: object = ()
    for server in sorted(servers, key=lambda s: (s.project is None, config.projects.index(s.project) if s.project else 0)):
        if server.project is not current:
            current = server.project
            title = f"{server.project.name} ({server.project.key})" if server.project and server.project.name != server.project.key else (server.project.name if server.project else "Other")
            lines += [f"# ── {title} ".ljust(60, "─"), ""]
        aliases = [full_alias(alias, config) for alias in server.aliases]
        lines.append("Host " + " ".join(aliases))
        lines.append(f"  User {server.user}:{server.target}")
        if server.port:
            lines.append(f"  Port {server.port}")
        if server.identity_file:
            lines.append(f"  IdentityFile {server.identity_file}")
        # The shared banner rules below go by the alias. Only a server they would get wrong
        # (a custom alias, or an env override) needs its own banner line.
        wanted = server.env if server.env in config.banners else "default"
        if any(_banner_by_pattern(alias, patterns) != wanted for alias in aliases):
            lines.append(f"  LocalCommand {_banner_command(*config.banners[wanted])}")
        lines.append("")

    lines += [f"# ── Shared settings for {config.host} ".ljust(60, "─"), ""]
    lines += ["# Login banners. Only Warpgate logins have a ':' in the user, so `user *:*` limits these to them.", ""]
    for env, globs in patterns:
        lines.append(f"Match user *:* originalhost {','.join(globs)}")
        lines.append(f"  LocalCommand {_banner_command(*config.banners[env])}")
        lines.append("")
    lines += [
        "# Every alias above goes to the gateway; anything without an environment gets this banner.",
        "Match user *:*",
        f"  HostName {config.host}",
        f"  LocalCommand {_banner_command(*config.banners['default'])}",
        "",
    ]
    if config.interface:
        lines += [
            "# Fails fast when the VPN is down: instead of connecting (which would hang until the",
            "# TCP timeout), print the warning and exit 255, for ssh, scp, rsync and git alike.",
            "# LogLevel ERROR only hides ssh's info-level \"Connection closed\" line after it; real errors still show.",
            "# ControlPersist no: with persist on, ssh sends the proxy's stderr (the warning) to /dev/null.",
            f'Match host {config.host} !exec "test -d /sys/class/net/{shlex.quote(config.interface)}"',
            f"  ProxyCommand {_vpn_down_proxy(config)}",
            "  LogLevel ERROR",
            "  ControlPersist no",
            "",
        ]
    lines += [
        "# Also covers plain `ssh -p PORT 'user:target@gateway'` without an alias.",
        "# Connection reuse keeps Warpgate's session logs from being flooded.",
        f"Match host {config.host}",
        f"  Port {config.port}",
        f"  IdentityFile {config.identity_file}",
        "  IdentitiesOnly yes",
        f"  ConnectTimeout {config.connect_timeout}",
        "  PermitLocalCommand yes",
        "  ControlMaster auto",
        "  ControlPath ~/.ssh/warpgate/cm-%C",
        "  ControlPersist 10m",
        "",
    ]
    return "\n".join(lines)


# ── Collisions with ~/.ssh/config ────────────────────────────────────────────


def existing_hosts(ssh_config: Path) -> set[str]:
    """Host names declared directly in ssh_config (not in files it includes)."""
    names: set[str] = set()
    if not ssh_config.is_file():
        return names
    for line in ssh_config.read_text(encoding="utf-8", errors="replace").splitlines():
        parts = line.split("#", 1)[0].split()
        if len(parts) >= 2 and parts[0].lower() == "host":
            names.update(part for part in parts[1:] if not any(char in part for char in "*?!"))
    return names


def check_collisions(config: Config, servers: list[Server], ssh_config: Path) -> None:
    taken = existing_hosts(ssh_config)
    clashes = sorted(full_alias(alias, config) for server in servers for alias in server.aliases if full_alias(alias, config) in taken)
    if clashes:
        raise ToolError(f"alias already used in {ssh_config}: {', '.join(clashes)}. Rename it with `alias = ...` or remove the old Host.")


# ── Adding targets from pasted text ──────────────────────────────────────────


def parse_pasted(text: str) -> list[str]:
    found: list[str] = []
    for line in text.splitlines():
        line = line.strip()
        if not line or line.startswith("#"):
            continue
        if "@" in line:
            found += PASTED_TARGET.findall(line)
        elif TARGET_PATTERN.match(line):
            found.append(line)
    return list(dict.fromkeys(found))


def _group_for(target: str, config: Config) -> str:
    project, _, _ = derive(target, config)
    return project.name if project else "other"


def add_targets(path: Path, names: list[str]) -> list[str]:
    """Add new names to [targets], each in its project's list, keeping comments and layout.

    A missing list is created at the end of the file, so [targets] has to stay the last table.
    """
    config = load_config(path)
    new = [name for name in names if name not in config.targets]
    if not new:
        return []
    lines = path.read_text(encoding="utf-8").splitlines(keepends=True)
    header = next((i for i, line in enumerate(lines) if line.strip() == "[targets]"), None)
    if header is None:
        lines += ["\n[targets]\n"]
        header = len(lines) - 1

    by_group: dict[str, list[str]] = {}
    for name in new:
        by_group.setdefault(_group_for(name, config), []).append(name)
    for group, members in by_group.items():
        entries = [f'  "{name}",\n' for name in members]
        start = next((i for i in range(header, len(lines)) if re.match(rf"^\s*{re.escape(group)}\s*=\s*\[", lines[i])), None)
        if start is None:
            if lines and not lines[-1].endswith("\n"):
                lines[-1] += "\n"
            lines += ["\n", f"{group} = [\n", *entries, "]\n"]
            continue
        end = next((i for i in range(start + 1, len(lines)) if lines[i].strip() == "]"), None)
        if end is None or "]" in lines[start]:
            raise ToolError(f"{path}: add needs `{group} = [` and its closing `]` on separate lines")
        lines[end:end] = entries

    updated = "".join(lines)
    try:
        listed = [name for group in tomllib.loads(updated).get("targets", {}).values() for name in group]
    except tomllib.TOMLDecodeError as exc:
        raise ToolError(f"{path}: adding would break the file ({exc}); nothing written") from None
    if any(name not in listed for name in new):  # e.g. [targets] is not the last table
        raise ToolError(f"{path}: couldn't place the new targets inside [targets]; keep [targets] as the last section")
    _backup(path)
    path.write_text(updated, encoding="utf-8")
    return new


# ── Writing ──────────────────────────────────────────────────────────────────


def _backup(path: Path) -> Path | None:
    if not path.exists():
        return None
    directory = backup_root() / datetime.now().strftime("%Y%m%d-%H%M%S")
    directory.mkdir(parents=True, exist_ok=True)
    destination = directory / path.name
    shutil.copy2(path, destination)
    return destination


def write_output(output: Path, content: str, *, assume_yes: bool, force: bool) -> bool:
    current = output.read_text(encoding="utf-8") if output.exists() else ""
    if current == content:
        print(f"{output} is up to date.")
        return False
    if current and not current.startswith("# Generated by warpgate-ssh") and not force:
        raise ToolError(f"{output} was not written by warpgate-ssh. Rerun with --force to replace it (a backup is kept).")
    sys.stdout.writelines(difflib.unified_diff(current.splitlines(True), content.splitlines(True), str(output), "generated"))
    if not assume_yes:
        if not sys.stdin.isatty():
            raise ToolError("not a terminal; rerun with --yes to write without asking")
        if input(f"\nWrite {output}? [y/N] ").strip().lower() not in ("y", "yes"):
            print("Nothing written.")
            return False
    backup = _backup(output)
    output.parent.mkdir(parents=True, exist_ok=True)
    output.write_text(content, encoding="utf-8")
    print(f"Wrote {output}" + (f" (previous copy: {backup})" if backup else ""))
    return True


def print_list(config: Config, servers: list[Server]) -> None:
    rows = [(", ".join(full_alias(a, config) for a in s.aliases), s.target, s.env or "-") for s in servers]
    widths = [max(len(row[i]) for row in rows + [("ALIAS", "TARGET", "ENV")]) for i in range(3)]
    for row in [("ALIAS", "TARGET", "ENV"), *rows]:
        print("  ".join(cell.ljust(width) for cell, width in zip(row, widths)).rstrip())


