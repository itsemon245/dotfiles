    parser.add_argument("--config", type=Path, default=None, help="TOML to read (default: ~/.ssh/warpgate/hosts.toml)")
    parser.add_argument("--output", type=Path, default=None, help="file to write (default: ~/.ssh/warpgate/hosts.conf)")
    parser.add_argument("--ssh-config", type=Path, default=None, help="checked for alias clashes (default: ~/.ssh/config)")
    parser.add_argument("--list", action="store_true", help="print target -> alias and exit")
    parser.add_argument("--check", action="store_true", help="exit 1 if the output is out of date; write nothing")
    parser.add_argument("--yes", "-y", action="store_true", help="write without asking")
    parser.add_argument("--force", action="store_true", help="replace an output file warpgate-ssh did not write")
    args = parser.parse_args(argv)

    config_path = expand(args.config) if args.config else default_config_path()
    output = expand(args.output) if args.output else default_output_path()
    ssh_config = expand(args.ssh_config) if args.ssh_config else home() / ".ssh" / "config"

    if args.command == "add":
        if sys.stdin.isatty():
            print("Paste the ssh lines or target names, then press Ctrl-D:", file=sys.stderr)
            pasted = sys.stdin.read()
            sys.stdin = open("/dev/tty")  # so the write prompt below can still ask
        else:
            pasted = sys.stdin.read()
        names = parse_pasted(pasted)
        if not names:
            raise ToolError("no target names found in the input")
        added = add_targets(config_path, names)
        print(f"Added {len(added)} new target(s) to {config_path}" + (": " + ", ".join(added) if added else " (all were already listed)"))

    config = load_config(config_path)
    servers = resolve(config)
    check_collisions(config, servers, ssh_config)
    if args.list:
        print_list(config, servers)
        return 0
    content = render(config, servers)
    if args.check:
        current = output.read_text(encoding="utf-8") if output.exists() else ""
        if current != content:
            print(f"{output} is out of date; run warpgate-ssh", file=sys.stderr)
            return 1
        print(f"{output} is up to date.")
        return 0
    write_output(output, content, assume_yes=args.yes, force=args.force)
    return 0
